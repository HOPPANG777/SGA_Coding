	// heap이나 data에 저장하면 되는데 우린 아직 동적 할당 아직 안배웠기 때문에
	// 정적 변수를 써보자
	// stack은 후입선출 구조
	// 스택에서 컴파일이 시작할때 스택프레임이 미리 정해져서 시작한다.
	// 프로그램이 데이터 영역이 생성되고 
	// 끝날때 사라진다.
	// Data->static
