int GetArithemeticSeries(int val)
{
	/*
	재귀함수의 방식을 생각해보자

	등차수열은 반대로 해도 똑같잖습니까
	Get(5) 호출

	1 + 2 + 3 + 4 + 5

	5 + 4 + 3 + 2 + 1

	5 + Get(4)

	val + Get(val - 1); // 점화식 // 불 붙이는 식 처음 딱 입력하면 끝날때까지 타들어간다.

	5 + Get(n)
	5 + 4 + Get(n)
	5 + 4 + 3 + Get(n)
	5 + 4 + 3 + 2 + Get(n)
	5 + 4 + 3 + 2 + 1 + Get(n)
	5 + 4 + 3 + 2 + 1 + 0 + Get(n)
	이런식으로 무한히 반복되지만
	이걸 끝어줘야한다.
	저기 위에 딱 1이 들어갔을때 멈추기 위해
	아래처럼 만약에 벨류 가 1일때
	리턴 벨류하면 멈춘다.

	우리가 가우스라 문제주면 바로 풀수있는것도아니고

	우리는 재귀구조를 써서 풀어야 한다.

	함수가 계속 호출되는 거다
	이러면 어떻게 되냐
	스택 오버플로우가 발생하게 된다.
	스택 오버플로우란
	스택 프레임은 1MB로 정해져있다
	굉장히 작아보이지만
	1메가가 충분하니까 이렇게 했겠지
	이레서 힙을 쓰게되는데 굉장히 크게 쓸수있기 때문이다.

	그래서 우린 재귀구조를 쓸때는 주의를 기울여야한다.

	그런데도 이러한 구조의 함수를 쓰는이유는
	설명하기가 참 어렵다
	재귀함수만에 참 깔끔한 무언가가 있다고 한다.
	딱 맞아떨어지게 되는
	묘한 가독성이 존재한다.

	하지만 모든 재귀함수는 사실 반복문 구조로 짤수있다
	하지만 고유의 가독성 때문에 사용된다.
	*/

	if (val == 1)
		return val;

	return val + GetArithemeticSeries(val - 1);	// 이렇게 하면 무한이 반복하면서 끝나지가 않는다.


}

int GetArithemeticSeriesTail(int val, int sum)
{
	/*
	꼬리 재귀의 핵심은 우리가 점화식을 사용했을때 연산이 들어갔을땐 컴파일러가 최적화를 못시켜준다.꼬리재귀가 있어도 최적화가 불가능하다.

	이래서 우리가 sum을 추가했다,

	최종 리턴에 연산이 포함되지 않는 구조일시

	컴파일러가 이걸 그냥 반복 구조로 바꿔버린다.

	최적화 구조를 넣게 되면 함수의 오버헤드와 스택 오버플로우를 방지할수있다.
	*/ 

	if (val == 0)
		return sum;

	return GetArithemeticSeriesTail(val - 1, val + sum);
}






