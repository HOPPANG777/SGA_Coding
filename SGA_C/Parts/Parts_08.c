	// 만약 전역 변수로 지정한 변수가 있다면 다른 지역에서 그 변수와 똑같은 이름의 변수를 선언했을때 컴퓨터는 둘의 이름이 똑같아서 
	// 햇갈려한다. 그러니 최대한 사용을 지양하는 쪽으로 개발해야 한다. 
